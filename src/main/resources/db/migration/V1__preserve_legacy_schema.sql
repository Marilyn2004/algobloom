-- Additive baseline. Existing rows and identifiers are never rewritten.
CREATE TABLE IF NOT EXISTS problems (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title varchar(255), difficulty varchar(255), pattern varchar(255), notes varchar(255),
 times_reviewed integer NOT NULL DEFAULT 0, solved boolean NOT NULL DEFAULT false,
 last_reviewed date, next_review_date date, platform varchar(255), external_problem_id varchar(255),
 slug varchar(255), url varchar(255),
 CONSTRAINT uk_problem_platform_external UNIQUE(platform,external_problem_id),
 CONSTRAINT uk_problem_platform_slug UNIQUE(platform,slug));
CREATE TABLE IF NOT EXISTS patterns (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 slug varchar(255) NOT NULL, name varchar(255) NOT NULL,
 CONSTRAINT uk_pattern_slug UNIQUE(slug));
CREATE TABLE IF NOT EXISTS problem_patterns (
 problem_id integer NOT NULL REFERENCES problems(id), pattern_id integer NOT NULL REFERENCES patterns(id),
 CONSTRAINT uk_problem_pattern UNIQUE(problem_id,pattern_id));
CREATE TABLE IF NOT EXISTS review_sessions (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 problem_id integer NOT NULL REFERENCES problems(id) ON DELETE CASCADE,
 reviewed_at timestamp, next_review_date date);
